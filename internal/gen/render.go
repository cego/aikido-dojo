package gen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"slices"

	"github.com/cego/aikido-dojo/internal/api"
	"github.com/cego/aikido-dojo/internal/ops"
	"github.com/cego/aikido-dojo/internal/overlay"
)

// Output is the generated catalog, one file each.
type Output struct {
	Ops     []byte // zz_ops.go
	Schemas []byte // schemas.json
	Search  []byte // search.json
}

// Generate builds the catalog from the spec's JSON and the overlay.
func Generate(specJSON []byte, overlays map[string]overlay.Op) (Output, error) {
	s, err := LoadSpec(specJSON)
	if err != nil {
		return Output{}, err
	}
	m, err := Build(s, overlays)
	if err != nil {
		return Output{}, err
	}
	var out Output
	if out.Ops, err = renderOps(m.Ops); err != nil {
		return Output{}, err
	}
	if out.Schemas, err = renderJSON(m.Schemas); err != nil {
		return Output{}, err
	}
	if out.Search, err = renderJSON(buildIndex(m)); err != nil {
		return Output{}, err
	}
	return out, nil
}

// renderJSON indents, so a spec change shows as a readable diff, and keeps
// <, > and & as they are, since nothing renders these files as HTML.
func renderJSON(v any) ([]byte, error) {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(v); err != nil {
		return nil, fmt.Errorf("encode JSON: %w", err)
	}
	return b.Bytes(), nil
}

var endNames = map[api.End]string{api.EndEmpty: "EndEmpty", api.EndHeader: "EndHeader", api.EndField: "EndField"}

var kindNames = map[ops.Kind]string{
	ops.String: "String", ops.Integer: "Integer", ops.Boolean: "Boolean",
	ops.StringList: "StringList", ops.IntegerList: "IntegerList",
}

func renderOps(all []ops.Op) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/tools/gen from spec/openapi.json and internal/overlay. DO NOT EDIT.\n\npackage catalog\n\nimport (\n")
	if slices.ContainsFunc(all, func(op ops.Op) bool { return op.Paging != nil }) {
		b.WriteString("\"github.com/cego/aikido-dojo/internal/api\"\n")
	}
	b.WriteString("\"github.com/cego/aikido-dojo/internal/ops\"\n)\n\n// All is every generated command, sorted by command.\nvar All = []ops.Op{\n")
	for _, op := range all {
		fmt.Fprintf(&b, "{\nID: %q,\nCommand: %q,\nMethod: %q,\nPath: %q,\n", op.ID, op.Command, op.Method, op.Path)
		for _, f := range []struct{ name, value string }{
			{"Summary", op.Summary}, {"Description", op.Description}, {"Help", op.Help},
			{"Scope", op.Scope}, {"BadRequestHint", op.BadRequestHint},
		} {
			if f.value != "" {
				fmt.Fprintf(&b, "%s: %q,\n", f.name, f.value)
			}
		}
		params(&b, "Args", op.Args)
		params(&b, "Flags", op.Flags)
		if body := op.Body; body != nil {
			fmt.Fprintf(&b, "Body: &ops.Body{Required: %t, Object: %t,\n", body.Required, body.Object)
			params(&b, "Fields", body.Fields)
			if len(body.Secret) > 0 {
				fmt.Fprintf(&b, "Secret: %#v,\n", body.Secret)
			}
			b.WriteString("},\n")
		}
		if p := op.Paging; p != nil {
			fmt.Fprintf(&b, "Paging: &api.Paging{End: api.%s, SizeParam: %q, Size: %d, Items: %q, More: %q},\n",
				endNames[p.End], p.SizeParam, p.Size, p.Items, p.More)
		}
		if op.Destructive {
			b.WriteString("Destructive: true,\n")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format the descriptors: %w", err)
	}
	return src, nil
}

func params(b *bytes.Buffer, name string, ps []ops.Param) {
	if len(ps) == 0 {
		return
	}
	fmt.Fprintf(b, "%s: []ops.Param{\n", name)
	for _, p := range ps {
		fmt.Fprintf(b, "{Name: %q, Kind: ops.%s, Required: %t, Usage: %q},\n", p.Name, kindNames[p.Kind], p.Required, p.Usage)
	}
	b.WriteString("},\n")
}
